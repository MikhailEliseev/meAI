def fill_template(
    template: str,
    client_data: Dict[str, Any],
    contract_data: Dict[str, Any],
) -> str:
    """
    Fill contract template with data

    Args:
        template: Contract template text
        client_data: Client information
        contract_data: Contract-specific data

    Returns:
        Filled contract text
    """
    # Merge all data
    data = {
        **get_default_contractor_data(),
        **get_default_contract_terms(),
        **client_data,
        **contract_data,
    }

    # Fill template
    result = template
    for key, value in data.items():
        placeholder = f"{{{{{key}}}}}"
        result = result.replace(placeholder, str(value))

    return result
